from __future__ import annotations

from datetime import datetime
from pathlib import Path

from emailctx.config import OutputSettings, Settings
from emailctx.pipeline.apply import apply_ops
from emailctx.pipeline.types import AcceptedOp
from emailctx.render.render import render_company
from emailctx.store.db import make_engine, make_sessionmaker
from emailctx.store.models import Company, Message, Project, Requirement

D1 = datetime(2026, 11, 16, 9, 0)
D2 = datetime(2026, 11, 19, 14, 0)


def _settings(tmp_path: Path, name: str) -> Settings:
    return Settings(db_path=tmp_path / f"{name}.db", output=OutputSettings(local_dir=None))


def _store(tmp_path: Path, name: str, reqs: list[tuple[str, str, str, str]]) -> str:
    """Insert requirements directly, in the given order, and render."""
    settings = _settings(tmp_path, name)
    sessions = make_sessionmaker(make_engine(settings.db_path))
    with sessions() as s:
        s.add(Company(company_id="acme", name="Acme"))
        s.add_all([Project(project_id=p, name=p.title(), company_id="acme") for p in ("atlas", "beacon")])
        s.add(Message(msg_id="m1", subject="Kickoff", date=D1, source="eml", ingested_at=D1))
        for project_id, req_id, text, cat in reqs:
            s.add(Requirement(project_id=project_id, req_id=req_id, seq=int(req_id[4:]), text=text,
                              normalized_text=text.lower(), category=cat, status="active",
                              version=1, source_ids=["m1"], updated_at=D1))
        s.commit()
        return render_company(s, "acme", settings)


def test_render_is_independent_of_insertion_order(tmp_path):
    # Two projects in one company can't be created through the app (one project per
    # company), but the renderer still lays such a store out with project sections.
    reqs = [
        ("beacon", "REQ-001", "Beacon one.", "functional"),
        ("atlas", "REQ-010", "Ten.", "functional"),
        ("atlas", "REQ-002", "Two.", "ui"),
        ("atlas", "REQ-001", "One.", "functional"),
        ("atlas", "REQ-003", "Three.", "mystery"),  # unknown category renders under Other
    ]
    a = _store(tmp_path, "a", reqs)
    b = _store(tmp_path, "b", list(reversed(reqs)))
    assert a == b
    atlas, beacon = a.index("## Atlas"), a.index("## Beacon")
    assert atlas < a.index("REQ-001** One.") < a.index("REQ-010") < a.index("### UI") < a.index("REQ-002")
    assert a.index("### Other") < a.index("REQ-003") < beacon < a.index("Beacon one.")
    assert "\r" not in a and a.endswith("\n") and not a.endswith("\n\n")


def test_rendered_document_shape(tmp_path):
    settings = _settings(tmp_path, "t")
    sessions = make_sessionmaker(make_engine(settings.db_path))
    with sessions() as s:
        s.add(Company(company_id="acme", name="Acme"))
        s.add(Project(project_id="atlas", name="Atlas", company_id="acme"))
        s.add(Project(project_id="quiet", name="Quiet", company_id="acme"))  # nothing yet: omitted
        s.add(Message(msg_id="m1@acme.com", subject="Atlas export", date=D1, source="eml", ingested_at=D1))
        s.add(Message(msg_id="sha256:" + "0" * 64, subject="Re:  Atlas\n export", date=D2,
                      source="eml", ingested_at=D2))
        s.flush()
        apply_ops(s, "atlas", [AcceptedOp("add", None, "Export must support CSV.", "functional",
                                          "quote", "m1@acme.com")], source_date=D1)
        apply_ops(s, "atlas", [AcceptedOp("modify", "REQ-001", "Export must support CSV and XLSX.",
                                          "functional", "quote", "sha256:" + "0" * 64)],
                  source_date=D2)
        s.commit()
        md = render_company(s, "acme", settings)
    assert md == (
        "# Acme: requirements\n"
        "\n"
        "<!-- Generated by emailctx from the requirements store. Manual edits are overwritten. -->\n"
        "\n"
        "## Functional\n"
        "\n"
        "- **REQ-001** Export must support CSV and XLSX.[^1][^2]\n"
        "\n"
        "## Changelog\n"
        "\n"
        "- 2026-11-16 · **REQ-001** added: Export must support CSV.[^1]\n"
        '- 2026-11-19 · **REQ-001** modified: "Export must support CSV." → '
        '"Export must support CSV and XLSX."[^2]\n'
        "\n"
        '[^1]: Email "Atlas export", 2026-11-16, ID `m1@acme.com`\n'
        '[^2]: Email "Re: Atlas export", 2026-11-19\n'  # no Message-ID: no ID shown
    )


def test_company_with_nothing_yet(tmp_path):
    settings = _settings(tmp_path, "e")
    sessions = make_sessionmaker(make_engine(settings.db_path))
    with sessions() as s:
        s.add(Company(company_id="acme", name="Acme"))
        s.commit()
        md = render_company(s, "acme", settings)
    assert md.endswith("_No requirements yet._\n")
